import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const MIG_DIR = 'supabase/migrations';
const OUT = 'supabase/install.sql';

// Discovered rather than hardcoded so a new migration can never be silently
// left out of install.sql (that is how 008_rbac_backfill.sql got missed once).
const files = readdirSync(MIG_DIR)
  .filter((f) => f.endsWith('.sql'))
  .sort();

/**
 * The individual migrations are written to run exactly once, so they use bare
 * CREATE TABLE / CREATE INDEX / CREATE POLICY. This installer makes the whole
 * bundle re-runnable so a failed attempt can be retried without hand-editing.
 */
function makeIdempotent(sql) {
  return sql
    .replace(/\bCREATE TABLE\s+(?!IF NOT EXISTS)/gi, 'CREATE TABLE IF NOT EXISTS ')
    .replace(/\bCREATE UNIQUE INDEX\s+(?!IF NOT EXISTS)/gi, 'CREATE UNIQUE INDEX IF NOT EXISTS ')
    .replace(/\bCREATE INDEX\s+(?!IF NOT EXISTS)/gi, 'CREATE INDEX IF NOT EXISTS ')
    // CREATE POLICY has no IF NOT EXISTS form, so emit a drop first.
    .replace(
      /\bCREATE POLICY\s+("[^"]+"|[A-Za-z_][\w$]*)\s+ON\s+([A-Za-z_][\w$.]*)/gi,
      (_, name, table) => `DROP POLICY IF EXISTS ${name} ON ${table};\nCREATE POLICY ${name} ON ${table}`,
    );
}

const parts = files.map((f) => {
  const raw = readFileSync(join(MIG_DIR, f), 'utf-8');
  return `-- ${'='.repeat(66)}\n-- from ${f}\n-- ${'='.repeat(66)}\n${makeIdempotent(raw).trim()}\n`;
});

const header = `-- ============================================================
-- install.sql  --  GENERATED, DO NOT EDIT BY HAND
--
-- Single-shot installer for the BSP Inventory ERP schema.
-- Generated by: node scripts/build-install-sql.mjs
-- Regenerate after editing anything in supabase/migrations/.
--
-- HOW TO USE
--   Supabase dashboard -> SQL Editor -> New query
--   Open this file, select all, paste, press Run.
--
-- Equivalent to, and idempotent with, running:
--   npx supabase db push
--
-- Safe to run more than once: CREATE TABLE / INDEX / POLICY are guarded and
-- functions use CREATE OR REPLACE.
--
-- Apply supabase/seed/demo_data.sql separately if you want sample data.
-- ============================================================

BEGIN;

`;

const footer = `
COMMIT;
`;

writeFileSync(OUT, header + parts.join('\n') + footer, 'utf8');

const stat = readFileSync(OUT, 'utf8');
console.log(`wrote ${OUT}`);
console.log(`  bytes      : ${stat.length.toLocaleString()}`);
console.log(`  lines      : ${stat.split('\n').length.toLocaleString()}`);
console.log(`  $$ blocks  : ${(stat.match(/\$\$/g) || []).length / 2}`);
console.log(`  balanced   : ${(stat.match(/\$\$/g) || []).length % 2 === 0 ? 'yes' : 'NO'}`);
console.log(`  policies   : ${(stat.match(/CREATE POLICY/gi) || []).length} (each with a DROP guard: ${
  (stat.match(/DROP POLICY IF EXISTS/gi) || []).length
})`);
console.log(`  tables     : ${(stat.match(/CREATE TABLE IF NOT EXISTS/gi) || []).length}`);
